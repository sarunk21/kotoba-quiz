// Determine the JLPT level of a word based on its kanji components
export function getWordJLPTLevel(kanji: string, chapter?: string): 'N5' | 'N4' | 'N3' | 'N2' | 'N1' {
  // If the chapter explicitly mentions a level, use it! (e.g. "JLPT N5", "Bab 1 - N5")
  if (chapter) {
    const match = chapter.toUpperCase().match(/N[1-5]/)
    if (match) {
      return match[0] as any
    }
  }

  if (!kanji || kanji === '') return 'N5'

  // Extract kanji characters (exclude Hiragana/Katakana)
  const kanjiChars = kanji.split("").filter(char => {
    const code = char.charCodeAt(0)
    // Basic kanji unicode range
    return code >= 0x4e00 && code <= 0x9faf
  })

  if (kanjiChars.length === 0) return 'N5' // Words in kana default to N5

  // Determine the highest level of all components (where N1 is highest, N5 is lowest)
  let levelScore = 5 // starts at N5

  for (const char of kanjiChars) {
    if (JLPT_KANJI_N5.has(char)) {
      levelScore = Math.min(levelScore, 5)
    } else if (JLPT_KANJI_N4.has(char)) {
      levelScore = Math.min(levelScore, 4)
    } else if (JLPT_KANJI_N3.has(char)) {
      levelScore = Math.min(levelScore, 3)
    } else if (JLPT_KANJI_N2.has(char)) {
      levelScore = Math.min(levelScore, 2)
    } else {
      levelScore = Math.min(levelScore, 1) // N1 or unclassified
    }
  }

  // Map back to level string
  return `N${levelScore}` as any
}
